"""Real PostgreSQL migration checks in disposable databases, never the application DB.

Run from the repository: python .../tests/test_products_unification_postgres.py
Requires the local proyecto_jupiter_db container. Every test creates its own database.
"""
import os
from pathlib import Path
import subprocess
import unittest
from uuid import uuid4

APP = Path(__file__).resolve().parents[1]
SQL = (APP / 'docker/init-scripts/init.sql').read_text(encoding='utf-8')
CONTAINER = os.getenv('PRODUCTS_TEST_PG_CONTAINER', 'proyecto_jupiter_db')
USER = os.getenv('PRODUCTS_TEST_PG_USER', 'admin')

LEGACY = """
CREATE TABLE products (
 product_id varchar(20) PRIMARY KEY, product_name varchar(150) NOT NULL,
 description varchar(500) NOT NULL, product_category varchar(50) NOT NULL,
 brand varchar(50), sku varchar(50) UNIQUE NOT NULL,
 product_cost_usd numeric(12,2), selling_price_usd numeric(12,2),
 created_at timestamp DEFAULT CURRENT_TIMESTAMP, updated_at timestamp DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE productos (
 pk_product bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 cdgo_producto_externo varchar(200), name_product varchar(200) NOT NULL,
 description_product varchar(1000), disabled boolean NOT NULL DEFAULT false,
 price numeric(18,4) DEFAULT 0, unit integer NOT NULL DEFAULT 1,
 final_price numeric(18,4) DEFAULT 0, discount numeric(18,4) DEFAULT 0,
 discount_end_date timestamptz, fk_currency integer NOT NULL DEFAULT 1,
 currency varchar(50), user_rating numeric(10,2) NOT NULL DEFAULT 0,
 link varchar(255), creation_date timestamptz DEFAULT CURRENT_TIMESTAMP,
 fk_last_update_user bigint NOT NULL DEFAULT 1,
 last_update timestamptz DEFAULT CURRENT_TIMESTAMP,supplier varchar(200));
CREATE TABLE migration_operational_child (
 product_id bigint REFERENCES productos(pk_product) ON DELETE RESTRICT);
CREATE TABLE migration_analytical_child (
 product_id varchar(20) REFERENCES products(product_id) ON DELETE CASCADE);
INSERT INTO productos(pk_product,cdgo_producto_externo,name_product,description_product,price,final_price,currency)
 VALUES (42,'PRD1','Shared','Description',10.1234,15.5678,'EUR'),
        (100,NULL,'No external code',NULL,1,2,'USD');
INSERT INTO products(product_id,product_name,description,product_category,brand,sku,product_cost_usd,selling_price_usd)
 VALUES ('PRD1','Shared','Description','Category','Brand','SKU1',3,4),
        ('PRD2','Analytical only','Second description','Other','Other brand','SKU2',5,6);
INSERT INTO migration_operational_child VALUES (42);
INSERT INTO migration_analytical_child VALUES ('PRD2');
"""


class ProductsUnificationPostgresTests(unittest.TestCase):
    def psql(self, sql, database=None, check=True):
        result = subprocess.run(
            ['docker', 'exec', '-i', CONTAINER, 'psql', '-X', '-qAt',
             '-v', 'ON_ERROR_STOP=1', '-U', USER, '-d', database or self.database],
            input=sql, encoding='utf-8', capture_output=True)
        if check and result.returncode:
            self.fail(result.stderr[-6000:])
        return result

    def setUp(self):
        self.database = 'test_products_' + uuid4().hex[:12]
        self.psql(f'CREATE DATABASE {self.database}', 'postgres')

    def tearDown(self):
        self.psql(f'DROP DATABASE {self.database} WITH (FORCE)', 'postgres')

    def scalar(self, sql):
        return self.psql(sql).stdout.strip()

    def test_fresh_install_repeat_and_updatable_contract(self):
        self.psql(SQL)
        self.psql(SQL)
        self.assertEqual(self.scalar("SELECT relkind FROM pg_class WHERE oid='productos'::regclass"), 'v')
        self.assertEqual(self.scalar("SELECT relkind FROM pg_class WHERE oid='products'::regclass"), 'r')
        value = self.scalar("INSERT INTO productos(name_product) VALUES ('Created through API contract') RETURNING pk_product")
        self.assertEqual(self.scalar(f"SELECT product_name FROM products WHERE id={value}"), 'Created through API contract')
        self.psql(f"UPDATE productos SET name_product='Updated',price=12.1234 WHERE pk_product={value}")
        self.assertEqual(self.scalar(f'SELECT price FROM products WHERE id={value}'), '12.1234')
        self.psql(f'DELETE FROM productos WHERE pk_product={value}')
        self.assertEqual(self.scalar('SELECT count(*) FROM products'), '0')

    def test_upgrade_preserves_ids_relations_money_and_sequence(self):
        self.psql(LEGACY)
        self.psql(SQL)
        self.psql(SQL)
        self.assertEqual(self.scalar('SELECT count(*) FROM products'), '3')
        self.assertEqual(self.scalar("SELECT id FROM products WHERE product_id='PRD1'"), '42')
        self.assertEqual(self.scalar("SELECT price||'|'||final_price||'|'||currency||'|'||product_cost_usd FROM products WHERE id=42"), '10.1234|15.5678|EUR|3.0000')
        self.assertEqual(self.scalar("SELECT product_name FROM products WHERE id=100"), 'No external code')
        self.assertEqual(self.scalar("SELECT count(*) FROM migration_operational_child c JOIN products p ON c.product_id=p.id"), '1')
        self.assertEqual(self.scalar("SELECT count(*) FROM migration_analytical_child c JOIN products p ON c.product_id=p.product_id"), '1')
        self.assertGreater(int(self.scalar("INSERT INTO productos(name_product) VALUES ('Next') RETURNING pk_product")), 101)
        denied = self.psql('DELETE FROM products WHERE id=42', check=False)
        self.assertNotEqual(denied.returncode, 0)
        self.psql("DELETE FROM products WHERE product_id='PRD2'")
        self.assertEqual(self.scalar('SELECT count(*) FROM migration_analytical_child'), '0')
        self.assertEqual(self.scalar("SELECT count(*) FROM pg_constraint WHERE contype='f' AND confrelid='productos'::regclass"), '0')

    def test_conflicts_roll_back_without_changing_legacy_tables(self):
        self.psql(LEGACY + "UPDATE products SET product_name='Conflicting name' WHERE product_id='PRD1';")
        failed = self.psql(SQL, check=False)
        self.assertNotEqual(failed.returncode, 0)
        self.assertIn('Conflicting product', failed.stderr)
        self.assertEqual(self.scalar("SELECT relkind FROM pg_class WHERE oid='productos'::regclass"), 'r')
        self.assertEqual(self.scalar('SELECT count(*) FROM productos'), '2')
        self.assertEqual(self.scalar('SELECT count(*) FROM products'), '2')
        self.assertEqual(self.scalar("SELECT to_regclass('products_unified') IS NULL"), 't')

    def test_unknown_dependency_causes_safe_rollback(self):
        self.psql(LEGACY + 'CREATE VIEW custom_catalog AS SELECT * FROM productos;')
        failed = self.psql(SQL, check=False)
        self.assertNotEqual(failed.returncode, 0)
        self.assertIn('depend', failed.stderr)
        self.assertEqual(self.scalar('SELECT count(*) FROM custom_catalog'), '2')

    def test_custom_database_business_rule_is_not_silently_dropped(self):
        self.psql(LEGACY + 'ALTER TABLE productos ADD CONSTRAINT custom_price CHECK (price >= 0);')
        failed = self.psql(SQL, check=False)
        self.assertNotEqual(failed.returncode, 0)
        self.assertIn('explicit migration', failed.stderr)
        self.assertEqual(self.scalar('SELECT count(*) FROM productos'), '2')

    def test_analytical_only_installation(self):
        self.psql(LEGACY.split('CREATE TABLE productos')[0])
        self.psql("INSERT INTO products(product_id,product_name,description,product_category,sku) VALUES ('PRD9','Nine','','','S9')")
        self.psql(SQL)
        self.assertEqual(self.scalar("SELECT name_product FROM productos WHERE cdgo_producto_externo='PRD9'"), 'Nine')

    def test_operational_only_installation(self):
        fixture = LEGACY.split('CREATE TABLE productos', 1)[1].split('CREATE TABLE migration_operational_child', 1)[0]
        self.psql('CREATE TABLE productos' + fixture)
        self.psql("INSERT INTO productos(pk_product,name_product) VALUES (500,'Only operational')")
        self.psql(SQL)
        self.assertEqual(self.scalar('SELECT product_name FROM products WHERE id=500'), 'Only operational')
        self.assertEqual(self.scalar("INSERT INTO productos(name_product) VALUES ('Next') RETURNING pk_product"), '501')

    def test_application_grants_survive_table_and_view_replacement(self):
        role = 'products_app_' + uuid4().hex[:12]
        self.psql(f'CREATE ROLE {role}', 'postgres')
        self.addCleanup(lambda: self.psql(f'DROP ROLE {role}', 'postgres'))
        self.psql(LEGACY)
        self.psql(f'GRANT USAGE ON SCHEMA public TO {role}; GRANT SELECT,INSERT,UPDATE,DELETE ON productos,products TO {role}')
        self.psql(SQL)
        value = self.scalar(f"SET ROLE {role}; INSERT INTO productos(name_product) VALUES ('Application role') RETURNING pk_product")
        self.assertGreater(int(value), 101)
        self.assertEqual(self.scalar(f"SET ROLE {role}; SELECT name_product FROM productos WHERE pk_product={value}"), 'Application role')

    def test_explicit_legacy_timezone_preserves_instant(self):
        self.psql(LEGACY)
        self.psql("UPDATE products SET created_at='2026-01-15 12:00:00' WHERE product_id='PRD2'")
        self.psql("SET TIME ZONE 'Europe/Madrid';\n" + SQL)
        self.assertEqual(self.scalar("SELECT created_at AT TIME ZONE 'UTC' FROM products WHERE product_id='PRD2'"), '2026-01-15 11:00:00')

    def test_schema_owner_can_migrate_without_superuser(self):
        role = 'products_migrator_' + uuid4().hex[:12]
        self.psql(f'CREATE ROLE {role}', 'postgres')
        self.addCleanup(lambda: self.psql(f'DROP ROLE {role}', 'postgres'))
        self.psql(f'GRANT CREATE ON DATABASE {self.database} TO {role}; GRANT ALL ON SCHEMA public TO {role}')
        # Database-level grants must be removed before DROP ROLE (database is
        # dropped by tearDown); schema and object grants disappear with it.
        self.psql(f'SET ROLE {role};\n' + LEGACY)
        self.psql(f'SET ROLE {role};\n' + SQL)
        self.assertEqual(self.scalar('SELECT count(*) FROM products'), '3')


if __name__ == '__main__':
    unittest.main(verbosity=2)
